import assert from 'node:assert/strict';
import { calculateCost, costPresets, compareQuotes, quoteVersions, materialGap, deliveryPlans } from '../src/business-engine.js';
const base = calculateCost(costPresets.luggage);
assert.equal(base.unitCost, 134);
assert.equal(base.quote, 178.67);
assert.ok(base.margin >= 25);
const discount = calculateCost({ ...costPresets.luggage, discount: 5 });
assert.equal(discount.actual, 169.74);
assert.ok(discount.margin < 25);
assert.equal(discount.total, discount.actual * 3000);
assert.ok(Math.abs(discount.profit - (discount.total - 402000)) < .00001);
assert.equal(calculateCost({ ...costPresets.luggage, qty: 6000 }).unitCost, 133);
assert.ok(calculateCost({ ...costPresets.luggage, discount: 50 }).profit < 0);
for (const data of [{ qty: 0 }, { qty: 1.5 }, { margin: 95 }, { material: NaN }, { discount: 100 }, { tooling: -1 }]) assert.throws(() => calculateCost({ ...costPresets.luggage, ...data }));
const comparison = compareQuotes(quoteVersions[1], quoteVersions[2]);
assert.equal(comparison.comparable, false);
assert.ok(Math.abs(comparison.normalizedDelta) < .00001);
assert.equal(compareQuotes(quoteVersions[1], { ...quoteVersions[1], price: 24 }).comparable, true);
assert.equal(compareQuotes(quoteVersions[0], { ...quoteVersions[0], currency: 'CNY' }).normalizedDelta, null);
assert.equal(materialGap(3000, 2400), 600);
assert.equal(materialGap(3000, 3100), 0);
assert.equal(deliveryPlans.find(p => p.id === 'expedite').extra, 600 * 6);
console.log('PASS: gross margin vs markup, rounding, discount, quantity allocation, invalid costs, quote comparability, material gap and expedited cost.');
