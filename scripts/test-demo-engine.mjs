import assert from 'node:assert/strict';
import { crmSamples, orderSamples, ledgerSample, extractCRM, inspectOrder, reconcile, csvCell } from '../src/demo-engine.js';

assert.equal(extractCRM(crmSamples.luggage).fields.find(f => f.id === 'quantity').value, '800 个');
assert.equal(extractCRM(crmSamples.luggage.replace('800', '1200')).fields.find(f => f.id === 'quantity').value, '1200 个');
assert.throws(() => extractCRM('  '));
assert.ok(extractCRM('不要800个，改成1200个').warnings.some(w => w.includes('否定')));
assert.equal(extractCRM('随便看看').fields.filter(f => f.value).length, 0);
const apparel = inspectOrder('apparel', orderSamples.apparel.text);
assert.equal(apparel.changes.find(c => c.field === 'L 码').after, '400 件');
assert.equal(apparel.changes.find(c => c.field === 'XL 码').after, '600 件');
assert.ok(apparel.summary.includes('变更后 1,000 件'));
assert.equal(inspectOrder('apparel', 'XL码增加100件').changes.length, 1, 'XL must not also match L');
assert.ok(inspectOrder('apparel', 'L码减少700件').changes.some(c => c.blocking));
assert.equal(inspectOrder('apparel', '你好').changes.length, 0);
assert.ok(inspectOrder('stroller', orderSamples.stroller.alternate).changes.some(c => c.blocking));
assert.ok(!inspectOrder('stroller', orderSamples.stroller.text).changes.some(c => c.blocking));
const report = reconcile(structuredClone(ledgerSample));
assert.equal(report.results.length, 3);
assert.equal(report.results.filter(r => r.issues.length).length, 2);
assert.ok(report.results[1].issues.some(i => i.includes('重复')));
assert.equal(report.total, 26600);
const corrected = structuredClone(ledgerSample);
corrected.receipts[0].qty = 1000;
corrected.statements[0].name = '黑色拉杆';
corrected.statements[0].price = 12.5;
corrected.statements.splice(2, 1);
assert.ok(reconcile(corrected).results.every(r => r.issues.length === 0));
corrected.statements[0].qty = -1;
assert.throws(() => reconcile(corrected));
corrected.statements[0].qty = '';
assert.throws(() => reconcile(corrected));
corrected.statements[0].qty = 1.2;
assert.throws(() => reconcile(corrected));
assert.equal(csvCell('=1+1'), '"\'=1+1"');
assert.equal(csvCell('a"b'), '"a""b"');
console.log('PASS: extraction edits, ambiguous input, size isolation, configuration conflicts, reconciliation, input validation and CSV escaping.');
